function segs(
  recordingId: string,
  rows: [number, number, string][],
): TranscriptSegment[] {
  return rows.map(([start, end, text], idx) => ({
    id: `${recordingId}-s${idx}`,
    idx,
    start_ms: start,
    end_ms: end,
    text,
    speaker_label: null,
  }));
}

